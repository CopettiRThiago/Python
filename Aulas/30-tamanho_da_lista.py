# Tamanho de uma Lista em Python

# Criando uma lista de números
numeros = [1, 2, 3, 4, 5]

# Descobrindo o tamanho da lista usando a função len()
# tamanho = len(lista)

tamanho_numeros = len(numeros)
print(f"O tamanho da lista de números é: {tamanho_numeros}")  # Output

# maior valor da lista
maior_numero = max(numeros)
print(f"O maior número da lista é: {maior_numero}")  # Output: O maior número da lista é: 5

# menor valor da lista
menor_numero = min(numeros)
print(f"O menor número da lista é: {menor_numero}")  # Output: O menor número da lista é: 1

